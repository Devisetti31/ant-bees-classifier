import urllib.request
import zipfile
from pathlib import Path

url = "https://download.pytorch.org/tutorial/hymenoptera_data.zip"

data_folder = Path("DaTA")

data_folder.mkdir(exist_ok=True)

zip_path = data_folder/'hymenoptera_data.zip'

if not zip_path.exists():
  urllib.request.urlretrieve(url, zip_path)

dataset_path = data_folder/'hymenoptera_data'
if not dataset_path.exists():
  with zipfile.ZipFile(zip_path) as z:
    z.extractall(data_folder)
print('DataSet ready at the location:',dataset_path)

import torch
import torch.nn as nn
import torch.optim as optim
from torchvision import datasets,transforms,models
from torch.utils.data import DataLoader
import matplotlib.pyplot as plt

train_transform = transforms.Compose(
    [
    transforms.Resize((224,224)),
    transforms.RandomHorizontalFlip(),
    transforms.ToTensor(),
    transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225])
    ]
      )

val_transform = transforms.Compose(
    [
    transforms.Resize((224,224)),
    transforms.ToTensor(),
    transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225])
    ]
      )

train_data = datasets.ImageFolder(root=dataset_path/'train',transform=train_transform)
val_data = datasets.ImageFolder(root=dataset_path/'val',transform=val_transform)

train_loder = DataLoader(train_data,batch_size=16,shuffle=True)
val_loder = DataLoader(val_data,batch_size=16,shuffle=False)

print(train_data.classes)
print(val_data.classes)
print('length of train dataset :',len(train_data))
print('length of val dataset :',len(val_data))

print(train_data.class_to_idx)

model = models.resnet18(
    weights=models.ResNet18_Weights.DEFAULT

)

for parameter in model.parameters():
  parameter.requires_grad = False

num_features = model.fc.in_features
num_features

model.fc = nn.Linear(num_features,2)

model.fc

device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')

device

model = model.to(device)

criterion = nn.CrossEntropyLoss()
optimizer = optim.Adam(model.fc.parameters(),lr=0.001)

print('Trainable Parameters : ',sum(p.numel() for p in model.parameters() if p.requires_grad))

num_epochs=5
for epoch in range(num_epochs):
  model.eval()
  model.fc.train()
  total_loss = 0.0
  correct_prediction = 0
  total_imgs = 0
  for images,labels in train_loder:
    images = images.to(device)
    labels = labels.to(device)
    optimizer.zero_grad()
    outputs = model(images)
    loss = criterion(outputs,labels)
    loss.backward()
    optimizer.step()
    total_loss += loss.item()*images.size(0)
    _,predicted = torch.max(outputs,1)
    total_imgs += labels.size(0)
    correct_prediction += (predicted==labels).sum().item()
    avg_loss = total_loss/total_imgs
  train_accuracy = (correct_prediction/total_imgs)*100
  train_loss = total_loss/total_imgs
  print(f"Epoch {epoch+1}/{num_epochs}")
  print(f"Train Loss: {train_loss:.4f} | Train Accuracy: {train_accuracy:.2f}%")

model.eval()
correct_prediction = 0
total_imgs = 0
with torch.no_grad():
  for images,labels in val_loder:
    images = images.to(device)
    labels = labels.to(device)
    outputs = model(images)
    _,predicted = torch.max(outputs,1)
    total_imgs += labels.size(0)
    correct_prediction += (predicted==labels).sum().item()
  val_accuracy = (correct_prediction/total_imgs)*100
  print(f"Validation Accuracy: {val_accuracy:.2f}%")

